import { z } from "zod";
import { EVENT_LIMITS, EVENT_SOURCES, EVENT_TYPES, INGEST_LIMITS } from "./constants";

/**
 * Pathname only: starts with "/", no query string or fragment (those can carry personal data),
 * no whitespace or control characters, bounded length.
 */
export const pageSchema = z
  .string()
  .min(1)
  .max(EVENT_LIMITS.maxPageLength)
  .regex(/^\/[A-Za-z0-9\-._~!$&'()*+,;=:@%/]*$/, "must be a pathname without query string or fragment");

export const productIdSchema = z
  .string()
  .min(1)
  .max(EVENT_LIMITS.maxProductIdLength)
  .regex(/^[a-z0-9][a-z0-9_-]*$/, "must be a lowercase slug");

export const isoTimestampSchema = z.iso
  .datetime({ offset: true })
  .refine((value) => !Number.isNaN(Date.parse(value)), "must be a valid timestamp");

/** The contract of every message on the `website-events` topic. */
export const eventSchema = z
  .strictObject({
    /** UUID, generated by the client and preserved on retries so consumers can deduplicate. */
    eventId: z.uuid(),
    type: z.enum(EVENT_TYPES),
    timestamp: isoTimestampSchema,
    /** Pseudonymous browser session id; also the Kafka message key. */
    sessionId: z.uuid(),
    page: pageSchema,
    productId: productIdSchema.optional(),
    source: z.enum(EVENT_SOURCES),
  })
  .superRefine((event, ctx) => {
    if ((event.type === "product_click" || event.type === "add_to_cart") && !event.productId) {
      ctx.addIssue({
        code: "custom",
        path: ["productId"],
        message: `productId is required for ${event.type} events`,
      });
    }
  });

export type WebsiteEvent = z.infer<typeof eventSchema>;

/** Body of POST /api/events. */
export const ingestRequestSchema = z.strictObject({
  events: z.array(eventSchema).min(1).max(INGEST_LIMITS.maxBatchSize),
  /** Required when `source` is "simulator": identifies one generator run for per-run limits. */
  runId: z.uuid().optional(),
});

export type IngestRequest = z.infer<typeof ingestRequestSchema>;

/** Timestamp window check used by the server on top of the schema. Returns an error message or null. */
export function checkTimestampWindow(timestamp: string, now: number = Date.now()): string | null {
  const time = Date.parse(timestamp);
  if (time < now - EVENT_LIMITS.maxEventAgeMs) return "timestamp is older than 24 hours";
  if (time > now + EVENT_LIMITS.maxFutureSkewMs) return "timestamp is in the future";
  return null;
}
